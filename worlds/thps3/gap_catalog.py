"""generate the client catalogue from the APWorld's gap definitions"""

import hashlib
import json
from pathlib import Path

from .data import GOAL_BY_LEVEL_AND_ID
from .locations import ALL_GAPS, GAP_LOCATION_NAME_TO_ID


def _row_json() -> tuple[str, ...]:
    return tuple(
        json.dumps(
            {
                "level": gap.level_key,
                "checksum": gap.checksum,
                "name": gap.name,
                "location_id": GAP_LOCATION_NAME_TO_ID[gap.location_name],
                "any_items": sorted(gap.required_trick_items),
                "all_items": sorted(gap.required_all_trick_items),
                "goal_items": [
                    GOAL_BY_LEVEL_AND_ID[(gap.level_key, goal_id)].item_name
                    for goal_id in sorted(gap.required_goal_ids)
                ],
            },
            separators=(",", ":"),
        )
        for gap in sorted(
            ALL_GAPS, key=lambda gap: GAP_LOCATION_NAME_TO_ID[gap.location_name]
        )
    )


_ROWS = _row_json()
GAP_CATALOG_FINGERPRINT = hashlib.sha256("\n".join(_ROWS).encode("ascii")).hexdigest()


def write_native_catalog(path: str) -> None:
    contents = [
        "// Generated by worlds.thps3.gap_catalog. Edit the APWorld gap definitions.",
        f'inline constexpr char kGapCatalogFingerprint[] = "{GAP_CATALOG_FINGERPRINT}";',
        "inline constexpr const char* kGapCatalogRows[] = {",
        *(f'    R"gap({row})gap",' for row in _ROWS),
        "};",
        "",
    ]
    Path(path).write_text("\n".join(contents), encoding="ascii")
